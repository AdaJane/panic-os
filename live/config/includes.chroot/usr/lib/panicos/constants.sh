# --- Volume labels -----------------------------------------------------------

# ISO 9660 volume id of the live medium: upper case, at most 32 characters.
readonly PANICOS_ISO_LABEL=PANICOS
# Filesystem label of the persistence volume (ext4 allows 16 bytes).
# Deliberately not live-boot's default "persistence": another live stick's
# volume plugged into the same machine must never be adopted and written to.
readonly PANICOS_PERSISTENCE_LABEL=panicos-persist
# LUKS2 header label of an encrypted persistence volume. Fixed by live-boot:
# persistence-encryption=lukslabel only opens containers labelled exactly this.
readonly PANICOS_LUKS_LABEL=persistence
# Where live-boot mounts each persistence volume it uses, as <dir>/<device>.
readonly PANICOS_PERSISTENCE_MOUNT_DIR=/run/live/persistence
# Where live-boot mounts the live medium.
readonly PANICOS_LIVE_MEDIUM_MOUNT=/run/live/medium

# --- Persistence states (persistence.sh) -------------------------------------

# live-boot mounted a persistence volume: changes survive a reboot.
readonly PANICOS_PERSISTENCE_ACTIVE=active
# The operator chose a boot entry without persistence.
readonly PANICOS_PERSISTENCE_DISABLED=disabled
# Persistence was asked for but no volume was found: work would be lost.
readonly PANICOS_PERSISTENCE_MISSING=missing


# --- VM test protocol (tests/vm/boot-test) -----------------------------------
#
# The harness hands the guest a systemd credential through SMBIOS; the guest's
# panicos-selftest.service runs only when that credential is present, writes
# the lines below to the first serial port, then powers off.
#
#   PANICOS-BOOT firmware=<bios|uefi> secureboot=<0|1>
#   PANICOS-IDENTITY id=<os-release ID>
#   PANICOS-PERSISTENCE state=<active|disabled|missing> boots=<n>
#   PANICOS-DESKTOP running=<0|1> pkexec=<0|1>
#   PANICOS-SAFETY swaps=<n> foreign_mounts=<n> md_arrays=<n> dm_devices=<n>
#   <one line per failed tool, if any>
#   PANICOS-SELFTEST <PASS|FAIL>

# Also named in panicos-selftest.service (ConditionCredential=); a unit test
# keeps the two in step.
readonly PANICOS_SELFTEST_CREDENTIAL=panicos.selftest

readonly PANICOS_MARK_BOOT=PANICOS-BOOT
readonly PANICOS_MARK_IDENTITY=PANICOS-IDENTITY
# boots counts self-test runs recorded on this system's disk: it only exceeds
# 1 if state written during one boot was still there on the next.
readonly PANICOS_MARK_PERSISTENCE=PANICOS-PERSISTENCE
# running=1 once the window manager is up after the automatic login.
# pkexec=1 if the desktop user can then become root through polkit without
# being asked anything, which is how GParted starts from the menu.
readonly PANICOS_MARK_DESKTOP=PANICOS-DESKTOP
# What this boot did to disks other than the stick. Every count must be 0 on
# a stick with unencrypted or no persistence (an encrypted persistence volume
# is itself one dm device).
#   swaps           active swap areas
#   foreign_mounts  mounted block devices that are neither the live medium
#                   nor its persistence volume
#   md_arrays       assembled RAID arrays
#   dm_devices      device-mapper devices: LVM volumes, LUKS mappings
readonly PANICOS_MARK_SAFETY=PANICOS-SAFETY
readonly PANICOS_MARK_PASS='PANICOS-SELFTEST PASS'
readonly PANICOS_MARK_FAIL='PANICOS-SELFTEST FAIL'

readonly PANICOS_FIRMWARE_BIOS=bios
readonly PANICOS_FIRMWARE_UEFI=uefi

# --- Flashing ----------------------------------------------------------------

# The smallest persistence volume worth creating. A stick must hold the image
# plus at least this much.
readonly PANICOS_MIN_PERSISTENCE_BYTES=1073741824

# --- Claude Code (claude.sh) -------------------------------------------------

# Answers to yes/no questions asked of the system.
readonly PANICOS_YES=yes
readonly PANICOS_NO=no
# Not part of the image: installed on request from Anthropic's apt archive.
readonly PANICOS_CLAUDE_PACKAGE=claude-code
readonly PANICOS_CLAUDE_COMMAND=claude
# The archive's sources file, used to refresh that one archive only.
readonly PANICOS_CLAUDE_SOURCES=/etc/apt/sources.list.d/claude-code.list

# --- Identity ----------------------------------------------------------------

# The Debian release PanicOS is built from.
readonly PANICOS_DEBIAN_CODENAME=trixie
# ID in os-release. ID_LIKE=debian tells tools what it behaves like.
readonly PANICOS_OS_ID=panicos
# Generated by the build (scripts/build-iso) and installed as /etc/os-release
# by the 0300 hook. Kept under /usr/lib/panicos so that it is not Debian's
# /usr/lib/os-release, which a base-files upgrade rewrites.
readonly PANICOS_OS_RELEASE_SOURCE=/usr/lib/panicos/os-release
